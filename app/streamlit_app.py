def show_result(result):
    """Present model estimates without implying a clinical assessment."""
    label = result["prediction"]
    color, background, text_color = RISK_STYLES[label]
    st.subheader("Prediction results")
    st.markdown(
        f'<div class="risk-card" style="border-left-color: {color}; '
        f'background-color: {background}">'
        '<span class="risk-caption">PREDICTED RISK CATEGORY</span>'
        f'<div class="risk-value" style="color: {text_color}">{label} Risk</div>'
        '</div>',
        unsafe_allow_html=True,
    )
    st.caption("Result based on the last submitted student profile.")
    st.markdown("#### Estimated class probabilities")
    for category in ("Low", "Medium", "High"):
        probability = result["probabilities"].get(category, 0.0)
        name, value = st.columns([4, 1])
        name.write(f"{category} Risk")
        value.write(f"{probability:.1%}")
        st.progress(probability, text=f"{category} Risk: {probability:.1%}")
    st.caption(
        "These percentages are model estimates across three categories; "
        "they are not clinically validated probabilities."
    )
    st.write(
        f"The saved model placed this profile in the **{label} Risk** category "
        "based on patterns in its training data."
    )
    st.info(DISCLAIMER)


def go_to_assessment():
    st.session_state.page = "Risk Prediction"


def read_metadata():
    path = REPORTS_DIR / "best_model_metadata.json"
    if not path.is_file():
        return {}
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError) as error:
        st.warning(f"Could not read {path.name}: {error}")
        return {}


def dataset_size():
    """Count records from the actual dataset, if available in this environment."""
    if not DATASET_PATH.is_file():
        return None
    try:
        return len(pd.read_csv(DATASET_PATH, usecols=[0]))
    except (OSError, ValueError, pd.errors.ParserError) as error:
        st.warning(f"Could not read dataset: {error}")
        return None


